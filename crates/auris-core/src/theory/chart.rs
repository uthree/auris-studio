/// The catalogue entry with this name, accepting the Japanese names too.
pub fn catalog(name: &str) -> Option<Chart> {
    let normalised = match name.trim() {
        "丸サ" | "丸サ進行" => "marusa",
        "王道" | "王道進行" => "royal-road",
        "小悪魔" | "小悪魔進行" => "koakuma",
        "小室" | "小室進行" => "komuro",
        "カノン" | "カノン進行" | "pachelbel" => "canon",
        "純情" | "純情進行" => "junjo",
        "泣き" | "泣きの進行" => "naki",
        "50s" | "fifties" => "doo-wop",
        "blues12" | "twelve-bar" => "blues",
        other => other,
    };
    CATALOG
        .iter()
        .find(|entry| entry.name == normalised)
        .and_then(|entry| Chart::parse(entry.chart))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::time::TICKS_PER_QUARTER;

    /// One bar of four four, in ticks.
    const BAR: Ticks = Ticks(TICKS_PER_QUARTER * 4);

    fn key(text: &str) -> Key {
        Key::parse(text).unwrap()
    }

    fn chord_names(chart: &Chart, key_text: &str) -> Vec<String> {
        chart
            .resolve(key(key_text), BAR)
            .iter()
            .map(|event| event.chord.to_string())
            .collect()
    }

    #[test]
    fn a_chart_reads_bar_by_bar() {
        let chart = Chart::parse("| I | V | vi | IV |").unwrap();
        assert_eq!(chart.bar_count(), 4);
        assert_eq!(chord_names(&chart, "C major"), ["C", "G", "Am", "F"]);
    }

    #[test]
    fn outer_pipes_are_optional_and_whitespace_is_free() {
        let a = Chart::parse("| I | V |").unwrap();
        let b = Chart::parse("I | V").unwrap();
        let c = Chart::parse("  I  |  V  ").unwrap();
        assert_eq!(a.bars, b.bars);
        assert_eq!(b.bars, c.bars);
    }

    #[test]
    fn two_chords_in_a_bar_split_it_evenly() {
        let chart = Chart::parse("| I | ii V |").unwrap();
        let events = chart.resolve(key("C major"), BAR);
        assert_eq!(events.len(), 3);
        assert_eq!(events[0].start, Ticks::ZERO);
        assert_eq!(events[0].length, BAR);
        assert_eq!(events[1].start, BAR);
        assert_eq!(events[1].length, Ticks(BAR.raw() / 2));
        assert_eq!(events[2].start, BAR + Ticks(BAR.raw() / 2));
        assert_eq!(events[2].length, Ticks(BAR.raw() / 2));
        assert_eq!(events[2].end(), BAR * 2, "the bar adds up exactly");
    }

    #[test]
    fn three_chords_in_a_bar_still_add_up_exactly() {
        // 4/4 does not divide by three; the remainder goes to the last chord rather than
        // leaving a gap the scheduler would render as silence.
        let chart = Chart::parse("| I ii V |").unwrap();
        let events = chart.resolve(key("C major"), BAR);
        assert_eq!(events.len(), 3);
        assert_eq!(events.last().unwrap().end(), BAR);
        let total: i64 = events.iter().map(|event| event.length.raw()).sum();
        assert_eq!(total, BAR.raw());
    }

    #[test]
    fn fitting_repeats_a_loop_and_truncates_a_long_one() {
        let chart = Chart::parse("| I | V |").unwrap();
        assert_eq!(chart.fit_to(4).bar_count(), 4);
        assert_eq!(
            chord_names(&chart.fit_to(4), "C major"),
            ["C", "G", "C", "G"]
        );
        assert_eq!(chart.fit_to(1).bar_count(), 1);
        assert_eq!(chart.fit_to(0).bar_count(), 0);
    }

    #[test]
    fn every_catalogue_entry_parses_and_is_named_once() {
        let mut seen = Vec::new();
        for entry in CATALOG {
            let chart = Chart::parse(entry.chart)
                .unwrap_or_else(|| panic!("`{}` does not parse: {}", entry.name, entry.chart));
            assert!(!chart.is_empty(), "`{}` is empty", entry.name);
            assert!(
                !seen.contains(&entry.name),
                "`{}` is listed twice",
                entry.name
            );
            assert!(!entry.description.is_empty());
            seen.push(entry.name);
            // And it resolves in both a major and a minor key without panicking.
            assert!(!chart.resolve(key("C major"), BAR).is_empty());
            assert!(!chart.resolve(key("A minor"), BAR).is_empty());
        }
    }

    #[test]
    fn the_named_progressions_come_out_as_the_chords_they_are_famous_for() {
        assert_eq!(
            chord_names(&catalog("marusa").unwrap(), "C major"),
            ["Fmaj7", "E7", "Am7", "C7"],
            "丸サ進行 in C"
        );
        assert_eq!(
            chord_names(&catalog("royal-road").unwrap(), "C major"),
            ["Fmaj7", "G7", "Em7", "Am"],
            "王道進行 in C"
        );
        assert_eq!(
            chord_names(&catalog("axis").unwrap(), "C major"),
            ["C", "G", "Am", "F"]
        );
        assert_eq!(
            chord_names(&catalog("epic").unwrap(), "A minor"),
            ["Am", "F", "C", "G"]
        );
        assert_eq!(
            chord_names(&catalog("andalusian").unwrap(), "A minor"),
            ["Am", "G", "F", "E"],
            "the descending tetrachord, with a major dominant at the end"
        );
    }

    #[test]
    fn the_koakuma_pedal_puts_the_subdominant_under_the_dominant() {
        let events = catalog("koakuma").unwrap().resolve(key("C major"), BAR);
        // F - G/F - Em - Am: the bass stays on F for two bars, which is the whole point.
        assert_eq!(events[1].chord.to_string(), "G/F");
        assert_eq!(events[1].chord.bass_class().sharp_name(), "F");
    }

    #[test]
    fn the_junjo_bass_descends_stepwise() {
        let events = catalog("junjo").unwrap().resolve(key("C major"), BAR);
        let bass: Vec<&str> = events
            .iter()
            .map(|event| event.chord.bass_class().sharp_name())
            .collect();
        assert_eq!(bass, ["C", "B", "A", "G", "F", "E", "D", "G"]);
    }

    #[test]
    fn a_catalogue_entry_can_be_named_and_repeated() {
        let once = Chart::parse("@axis").unwrap();
        let twice = Chart::parse("@axis x2").unwrap();
        assert_eq!(once.bar_count(), 4);
        assert_eq!(twice.bar_count(), 8);
        assert_eq!(twice.bars[4], once.bars[0]);
        assert!(Chart::parse("@nonsense").is_none());
    }

    #[test]
    fn the_japanese_names_reach_the_same_charts() {
        assert_eq!(catalog("丸サ進行"), catalog("marusa"));
        assert_eq!(catalog("王道進行"), catalog("royal-road"));
        assert_eq!(catalog("小悪魔"), catalog("koakuma"));
    }

    #[test]
    fn a_chart_round_trips_through_its_text() {
        let chart = Chart::parse("| IVmaj7 | III7 | vi7 | I7 |").unwrap();
        assert_eq!(chart.to_string(), "| IVmaj7 | III7 | vi7 | I7 |");
        assert_eq!(Chart::parse(&chart.to_string()).unwrap().bars, chart.bars);
    }

    #[test]
    fn nonsense_is_rejected_rather_than_silently_dropped() {
        assert!(Chart::parse("| I | nonsense |").is_none());
        assert!(Chart::parse("").is_none());
        assert!(Chart::parse("| |").is_none());
    }
}
