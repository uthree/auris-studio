//! Chord charts: a progression written in numerals, and the catalogue of named ones.

use std::fmt;

use crate::time::Ticks;

use super::chord::Chord;
use super::key::Key;
use super::numeral::Numeral;

/// A progression, one bar per entry.
///
/// Chords inside a bar split it evenly, which is how a chart is read: `| Am | F G |` is two bars,
/// the second holding two chords of half a bar each.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Chart {
    /// The numerals, grouped by bar.
    pub bars: Vec<Vec<Numeral>>,
    /// Where the chart came from, which decides whether it may be rewritten.
    pub origin: ChartOrigin,
}

/// Where a chart came from.
#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub enum ChartOrigin {
    /// Typed by the user, or quoted from the catalogue. Never rewritten.
    ///
    /// This is what keeps a quoted progression sounding like the song it came from: colouring
    /// and cadence scheduling would turn 丸サ's floating loop into something that lands.
    Given,
    /// Generated by the composer, and therefore fair game for cadences and colour.
    Generated,
}

impl Chart {
    /// A chart from bars of numerals.
    pub fn new(bars: Vec<Vec<Numeral>>, origin: ChartOrigin) -> Self {
        Self { bars, origin }
    }

    /// How many bars the chart occupies.
    pub fn bar_count(&self) -> usize {
        self.bars.len()
    }

    /// `true` when the chart has no chords at all.
    pub fn is_empty(&self) -> bool {
        self.bars.iter().all(|bar| bar.is_empty())
    }

    /// Reads a chart: `| IVmaj7 | III7 | vi | I7 |`, or `@marusa` to name one.
    ///
    /// The outer pipes are optional and a bar may hold several chords. `@name x2` repeats a
    /// catalogue entry, which is how an eight-bar verse is written over a four-bar loop.
    pub fn parse(text: &str) -> Option<Self> {
        let text = text.trim();
        if let Some(rest) = text.strip_prefix('@') {
            // Split on whitespace, not on `x`: a name may contain one, and `@axis x2` must not
            // be read as the name `a` repeated `is x2` times.
            let (name, repeats) = match rest.split_once(char::is_whitespace) {
                Some((name, count)) => {
                    let repeats: usize = count.trim().trim_start_matches('x').parse().ok()?;
                    // A repeat count large enough to exhaust memory is a typo, not a request.
                    if !(1..=64).contains(&repeats) {
                        return None;
                    }
                    (name.trim(), repeats)
                }
                None => (rest.trim(), 1),
            };
            let chart = catalog(name)?;
            let bars = chart
                .bars
                .iter()
                .cycle()
                .take(chart.bars.len() * repeats.max(1))
                .cloned()
                .collect();
            return Some(Self::new(bars, ChartOrigin::Given));
        }

        let mut bars = Vec::new();
        for bar in text.split('|') {
            let bar = bar.trim();
            if bar.is_empty() {
                continue;
            }
            let mut chords = Vec::new();
            for symbol in bar.split_whitespace() {
                chords.push(Numeral::parse(symbol)?);
            }
            bars.push(chords);
        }
        (!bars.is_empty()).then(|| Self::new(bars, ChartOrigin::Given))
    }

    /// The chart repeated or truncated to exactly `bars` bars.
    ///
    /// Repeating rather than stretching: a four-bar loop under an eight-bar verse is played
    /// twice, which is what every band does and what every listener expects.
    pub fn fit_to(&self, bars: usize) -> Self {
        if self.bars.is_empty() || bars == 0 {
            return Self::new(Vec::new(), self.origin);
        }
        let fitted = self.bars.iter().cycle().take(bars).cloned().collect();
        Self::new(fitted, self.origin)
    }

    /// Where each chord falls, laid out from tick zero, before it is read against any key.
    ///
    /// `bar_ticks` is the length of one bar. Chords inside a bar divide it evenly, with any
    /// remainder given to the last chord so the bar always adds up exactly — a three-chord bar in
    /// 4/4 is 1280 + 1280 + 1280, and never 1280 + 1280 + 1279.
    ///
    /// Both [`Self::resolve`] and [`Harmony::stamp`](crate::harmony::Harmony::stamp) go through
    /// here, so a chart and the timeline stamped from it divide a bar the same way by
    /// construction rather than because two people wrote the same arithmetic twice.
    pub fn positions(&self, bar_ticks: Ticks) -> Vec<ChartSlot> {
        let mut slots = Vec::new();
        for (index, bar) in self.bars.iter().enumerate() {
            if bar.is_empty() {
                continue;
            }
            let bar_start = bar_ticks * index as i64;
            let share = Ticks(bar_ticks.raw() / bar.len() as i64);
            for (position, numeral) in bar.iter().enumerate() {
                let start = bar_start + share * position as i64;
                let end = if position + 1 == bar.len() {
                    bar_start + bar_ticks
                } else {
                    bar_start + share * (position + 1) as i64
                };
                slots.push(ChartSlot {
                    numeral: *numeral,
                    start,
                    length: end - start,
                    bar: index,
                });
            }
        }
        slots
    }

    /// The chords this chart means in `key`, laid out from tick zero.
    ///
    /// `bar_ticks` is the length of one bar; see [`Self::positions`] for how a bar is divided.
    pub fn resolve(&self, key: Key, bar_ticks: Ticks) -> Vec<HarmonicEvent> {
        self.positions(bar_ticks)
            .into_iter()
            .map(|slot| HarmonicEvent {
                numeral: slot.numeral,
                chord: slot.numeral.chord_in(key),
                key,
                start: slot.start,
                length: slot.length,
                bar: slot.bar,
            })
            .collect()
    }
}

/// Where one chord of a chart falls, before any key has been chosen.
///
/// This is [`HarmonicEvent`] minus the two things a key decides. Laying a chart onto a timeline
/// does not need them: the timeline stores numerals and reads them against whatever key is in
/// force where they land, which may not be one key for the whole chart.
#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub struct ChartSlot {
    /// The numeral written there.
    pub numeral: Numeral,
    /// Where it starts, from the beginning of the chart.
    pub start: Ticks,
    /// How long it sounds.
    pub length: Ticks,
    /// Which bar of the chart it falls in, counting from zero.
    pub bar: usize,
}

impl fmt::Display for Chart {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        for bar in &self.bars {
            f.write_str("| ")?;
            for numeral in bar {
                write!(f, "{numeral} ")?;
            }
        }
        f.write_str("|")
    }
}

/// One chord in time: what it is, where it is, and how long it lasts.
#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub struct HarmonicEvent {
    /// The numeral it was written as.
    pub numeral: Numeral,
    /// The chord that numeral means in this key.
    pub chord: Chord,
    /// The key it was resolved against, which a section may have transposed.
    pub key: Key,
    /// Where it starts, from the beginning of the section.
    pub start: Ticks,
    /// How long it sounds.
    pub length: Ticks,
    /// Which bar of the section it falls in.
    pub bar: usize,
}

impl HarmonicEvent {
    /// Position just past the end of the chord.
    pub fn end(&self) -> Ticks {
        self.start + self.length
    }

    /// `true` when `tick` falls inside the chord.
    pub fn contains(&self, tick: Ticks) -> bool {
        tick >= self.start && tick < self.end()
    }
}

/// A named progression from the catalogue.
pub struct CatalogEntry {
    /// The name the text format writes, after an `@`.
    pub name: &'static str,
    /// What it is, for a listing.
    pub description: &'static str,
    /// The chart, in the notation [`Chart::parse`] reads.
    pub chart: &'static str,
}

